"""
Amazon Wholesale Catalog Analyzer & Cloudflare D1 Pipeline
===========================================================
Multi-Module Architecture:

1. modules.entrypoint
   - Application launcher and top-level navigation hub.
   - Coordinates routing between the analysis, upload, and CRUD interfaces.

2. modules.analyzer
   - Data analysis and preparation engine (Current core features).
   - Ingests supplier wholesale price lists (CSV/Excel).
   - Enriches catalog items using Amazon SP-API or Simulation/Demo mode.
   - Computes FBA Pick & Pack fees, referral fees, sales velocity, profit, margin, and ROI.
   - Exports reports in the standardized 52-column Target Wholesale Excel format.

3. modules.uploader
   - Cloudflare D1 Database integration for persistence.
   - Ingests the 52-column output file generated by Module 2.
   - Validates data types, sanitizes payloads, and batches records.
   - Executes upsert queries against Cloudflare D1 SQLite database via REST API.

4. modules.crud
   - Cloudflare D1 Database CRUD operations and User Data Viewer.
   - Reads, filters, searches, updates, and deletes wholesale catalog records in D1.
   - Provides an interactive dashboard for users to inspect historical analyses and leads.
"""

__version__ = "2.0.0"
