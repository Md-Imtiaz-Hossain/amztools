"""
Module 5: Upload Data to MySQL Remote Database - Streamlit User Interface
=========================================================================
Purpose:
    Renders the Streamlit interface for Module 5 (Upload to Remote MySQL DB, e.g., Hostinger).
    Enables users to:
    - Input and test Remote MySQL credentials (Host, Port, Database Name, Username, Password)
    - Initialize the remote `wholesale_products` table schema in MySQL
    - Select source data: active in-memory results from Module 2 or uploaded Excel/CSV file
    - Inspect pre-flight validation status (valid ASINs, data types, column checks)
    - Execute the batch insert/upsert pipeline with a real-time progress bar and slot notifications
"""

import streamlit as st
import pandas as pd

from .config import MySQLDatabaseConfig
from .mysql_client import MySQLRemoteClient
from .uploader_service import MySQLUploaderService
from modules.uploader.file_parser import (
    parse_and_validate_analysis_file,
    validate_record_integrity,
)


def render_mysql_uploader_ui():
    """
    Renders the complete user interface for Module 5: Upload Data to MySQL Remote DB.
    """
    st.header("🐬 Module 5: Upload Data to MySQL Remote DB")
    st.markdown(
        "Upload the analyzed catalog data generated by Module 2 or upload a saved Target Excel/CSV file directly into your remote MySQL database (e.g., Hostinger MySQL)."
    )

    # --- SIDEBAR: MYSQL REMOTE DB CREDENTIALS ---
    st.sidebar.subheader("🔐 MySQL Remote DB Credentials")
    env_config = MySQLDatabaseConfig.from_env()

    mysql_host = st.sidebar.text_input(
        "MySQL Host Address",
        value=st.session_state.get("mysql_host", env_config.host),
        placeholder="srv1570.hstgr.io or 82.197.82.58",
        help="Remote MySQL hostname or IP address (e.g., srv1570.hstgr.io or 82.197.82.58 on Hostinger).",
        key="mysql_host_input",
    )
    mysql_port = st.sidebar.number_input(
        "MySQL Port",
        min_value=1,
        max_value=65535,
        value=int(st.session_state.get("mysql_port", env_config.port or 3306)),
        step=1,
        help="Standard MySQL TCP port is 3306.",
        key="mysql_port_input",
    )
    mysql_database = st.sidebar.text_input(
        "Database Name",
        value=st.session_state.get("mysql_database", env_config.database),
        placeholder="Database Name",
        help="Exact MySQL database name (e.g., u7421).",
        key="mysql_database_input",
    )
    mysql_user = st.sidebar.text_input(
        "User Name",
        value=st.session_state.get("mysql_user", env_config.user),
        placeholder="User Name",
        help="MySQL database username with INSERT/CREATE permissions.",
        key="mysql_user_input",
    )
    mysql_password = st.sidebar.text_input(
        "Password",
        value=st.session_state.get("mysql_password", env_config.password),
        type="password",
        help="Password for the MySQL user.",
        key="mysql_password_input",
    )

    st.sidebar.subheader("⚡ Upload Tuning")
    slot_size = st.sidebar.number_input(
        "Notification Slot Size (Records)",
        min_value=50,
        max_value=2000,
        value=int(st.session_state.get("mysql_slot_size", 500)),
        step=50,
        help="Divide large uploads into slots of this size. Gives a confirmation notification after each slot.",
        key="mysql_slot_size_input",
    )
    batch_size = st.sidebar.slider(
        "Batch Size (Rows per Transaction)",
        min_value=10,
        max_value=500,
        value=int(st.session_state.get("mysql_batch_size", env_config.batch_size or 100)),
        help="Number of rows executed per MySQL executemany() batch transaction.",
        key="mysql_batch_size_slider",
    )

    # Save to session state
    st.session_state["mysql_host"] = mysql_host.strip()
    st.session_state["mysql_port"] = int(mysql_port)
    st.session_state["mysql_database"] = mysql_database.strip()
    st.session_state["mysql_user"] = mysql_user.strip()
    st.session_state["mysql_password"] = mysql_password.strip()
    st.session_state["mysql_batch_size"] = int(batch_size)
    st.session_state["mysql_slot_size"] = int(slot_size)

    active_config = MySQLDatabaseConfig(
        host=st.session_state["mysql_host"],
        port=st.session_state["mysql_port"],
        database=st.session_state["mysql_database"],
        user=st.session_state["mysql_user"],
        password=st.session_state["mysql_password"],
        batch_size=int(batch_size),
    )
    client = MySQLRemoteClient(active_config)

    # Connection Test Button
    if st.sidebar.button("🧪 Test MySQL Connection", key="test_mysql_conn_btn", use_container_width=True):
        if not active_config.is_valid():
            st.sidebar.warning("Please provide Host, Database Name, User Name, and Password.")
        else:
            with st.sidebar.spinner("Connecting to Remote MySQL..."):
                success, msg = client.test_connection()
            if success:
                st.sidebar.success(msg)
            else:
                st.sidebar.error(msg)

    with st.sidebar.expander("🛠️ Database Maintenance", expanded=False):
        if st.button("Initialize MySQL Table Schema", key="mysql_init_schema_btn", use_container_width=True):
            if not active_config.is_valid():
                st.warning("Please configure your MySQL credentials first.")
            else:
                with st.spinner("Initializing wholesale_products table in Remote MySQL..."):
                    ok, msg = client.init_database_schema(force=True)
                if ok:
                    st.success(msg)
                else:
                    st.error(msg)

        st.markdown("---")
        st.markdown("**Clear MySQL Table**")
        confirm_clear = st.checkbox("Confirm wipe all MySQL data", key="mysql_confirm_clear_chk")
        if st.button(
            "🗑️ Clear wholesale_products Table",
            key="mysql_clear_table_btn",
            use_container_width=True,
            type="secondary",
        ):
            if not active_config.is_valid():
                st.warning("Please configure your MySQL credentials first.")
            elif not confirm_clear:
                st.warning("Please check 'Confirm wipe all MySQL data' first.")
            else:
                with st.spinner("Clearing wholesale_products table in MySQL..."):
                    ok, msg = client.clear_table()
                if ok:
                    st.success(msg)
                else:
                    st.error(msg)

    st.sidebar.markdown("---")

    # --- MAIN VIEW: DATA SOURCE SELECTION ---
    st.subheader("1. Select Dataset to Upload")

    pending_mysql = st.session_state.get("pending_mysql_upload")
    if pending_mysql is None:
        pending_mysql = st.session_state.get("pending_d1_upload")
    has_pending = pending_mysql is not None

    source_mode = st.radio(
        "Choose Data Source:",
        ["📦 In-Memory Analysis from Module 2", "📁 Upload Target Analysis File (.xlsx or .csv)"],
        index=0 if has_pending else 1,
        key="mysql_uploader_source_mode",
    )

    dataset_source = None

    if "In-Memory" in source_mode:
        if has_pending:
            dataset_source = pending_mysql
            st.success(f"✅ In-memory analysis loaded from Module 2 (**{len(dataset_source)} products** ready).")
        else:
            st.info(
                "ℹ️ No active analysis found in memory. You can switch to Module 2 to analyze a catalog, or upload a saved file below."
            )
    else:
        uploaded_analysis_file = st.file_uploader(
            "Upload Saved Target Analysis File (.xlsx or .csv)",
            type=["xlsx", "csv"],
            key="mysql_uploader_file_input",
            help="Upload an Excel or CSV file generated from Module 2.",
        )
        if uploaded_analysis_file:
            dataset_source = uploaded_analysis_file
            st.success(f"File `{uploaded_analysis_file.name}` uploaded.")

    if dataset_source is None:
        return

    # --- PRE-FLIGHT VERIFICATION ---
    st.subheader("2. Pre-Flight Data Validation & Preview")

    with st.spinner("Parsing and validating columns..."):
        try:
            parsed_records = parse_and_validate_analysis_file(dataset_source)
            integrity = validate_record_integrity(parsed_records)
            st.session_state["mysql_uploader_parsed_records"] = parsed_records
        except Exception as e:
            st.error(f"Error parsing source dataset: {e}")
            return

    # Metrics Row — all rows read from file are uploaded (zero filtering/deletion)
    total_rows_read = len(parsed_records)
    m1, m2, m3, m4, m5 = st.columns(5)
    m1.metric("Total Rows in File", f"{total_rows_read:,}")
    m2.metric("Rows Ready for MySQL", f"{total_rows_read:,}")
    m3.metric("Rows Without ASIN", f"{integrity['missing_asin_count']:,}")
    m4.metric("Unique ASINs", f"{integrity.get('unique_asin_count', 0):,}")
    m5.metric("Variations / Same ASIN", f"{integrity.get('duplicate_asin_count', 0):,}")

    if total_rows_read == 0:
        st.error("⚠️ The uploaded file is empty. Please verify the file.")
        return

    st.success(
        f"✅ **Full Dataset Mode Active**: All **{total_rows_read:,} rows** read from the file will be written to your MySQL database (0 rows filtered or skipped)."
    )

    effective_slot = int(st.session_state.get("mysql_slot_size", slot_size))
    total_valid = total_rows_read
    estimated_slots = max(1, (total_valid + effective_slot - 1) // effective_slot)

    if total_valid > effective_slot:
        st.info(
            f"💡 **Smart Slot Batching Active**: Dataset with **{total_valid:,} records** "
            f"will be written safely in slots of **{effective_slot} records** (~**{estimated_slots} slots**). "
            f"You will receive a notification and row confirmation every time {effective_slot} records are written to the MySQL database."
        )

    with st.expander("👁️ Preview Parsed Database Records (First 5 Rows)", expanded=True):
        preview_df = pd.DataFrame(parsed_records[:5])
        display_subcols = [
            c
            for c in [
                "asin",
                "product_id",
                "wholesaler_company_name",
                "brand",
                "title",
                "category",
                "sales_rank",
                "cost",
                "sell_price",
                "profit",
                "roi_pct",
            ]
            if c in preview_df.columns
        ]
        st.dataframe(preview_df[display_subcols] if display_subcols else preview_df, use_container_width=True)

    # --- UPLOAD EXECUTION ---
    st.subheader("3. Execute Remote MySQL Synchronization")

    c_opt1, c_opt2 = st.columns(2)
    with c_opt1:
        upload_mode_choice = st.radio(
            "Upload Strategy:",
            [
                "📥 Insert All Records (Preserve every catalog row & duplicate ASINs)",
                "🔄 Upsert / ON DUPLICATE KEY UPDATE",
            ],
            index=0,
            key="mysql_upload_mode_choice",
            help="Insert All Records guarantees that every valid catalog item is inserted into MySQL.",
        )
        upload_mode = "insert" if "Insert All" in upload_mode_choice else "upsert"

    with c_opt2:
        cleanup_choice = st.selectbox(
            "Existing Database Records Handling:",
            [
                "Keep existing database records (Append mode)",
                "Clear entire database table before upload (Fresh start - DB count matches file)",
                "Replace records for this wholesaler only",
            ],
            index=0,
            key="mysql_cleanup_choice",
            help="Choose whether to wipe previous records so your MySQL table count exactly matches this file.",
        )
        if "Clear entire" in cleanup_choice:
            clear_existing = "all"
        elif "Replace records for this wholesaler" in cleanup_choice:
            clear_existing = "wholesaler"
        else:
            clear_existing = "none"

    if clear_existing == "all":
        st.warning(
            "⚠️ **Notice**: The MySQL `wholesale_products` table will be truncated before uploading. Your database will contain only the records from this upload."
        )

    if not active_config.is_valid():
        st.warning(
            "⚠️ Please provide your **MySQL Host Address**, **Database Name**, **User Name**, and **Password** in the sidebar before starting the upload."
        )
        return

    if st.button("🚀 Start Upload to Remote MySQL DB", type="primary", key="start_mysql_upload_btn"):
        uploader_service = MySQLUploaderService(client)

        m_col1, m_col2, m_col3, m_col4 = st.columns(4)
        m_uploaded = m_col1.empty()
        m_slots = m_col2.empty()
        m_speed = m_col3.empty()
        m_eta = m_col4.empty()

        m_uploaded.metric("Uploaded Records", f"0 / {total_valid:,}")
        m_slots.metric("Completed Slots", f"0 / {estimated_slots}")
        m_speed.metric("Upload Speed", "0.0 rows/s")
        m_eta.metric("Estimated Time Left", "--")

        progress_bar = st.progress(0.0)
        status_text = st.empty()

        feed_expander = st.expander("📋 Live Slot Confirmations & Audit Log", expanded=True)
        feed_container = feed_expander.empty()
        slot_feed_messages = []

        def handle_slot_notification(info: dict):
            slot_num = info.get("slot_number", 1)
            t_slots = info.get("total_slots", 1)
            start_row = info.get("start_row", 1)
            end_row = info.get("end_row", 1)
            uploaded_now = info.get("slot_uploaded", 0)

            toast_text = f"✅ Slot {slot_num}/{t_slots}: Excel rows {start_row} to {end_row} uploaded to MySQL!"
            try:
                st.toast(toast_text, icon="🐬")
            except Exception:
                pass

            cum_uploaded = info.get("cumulative_uploaded", 0)
            tot_records = info.get("total_records", total_valid)
            speed = info.get("speed_records_per_sec", 0.0)
            eta_sec = info.get("eta_seconds", 0)

            m_uploaded.metric("Uploaded Records", f"{cum_uploaded:,} / {tot_records:,}")
            m_slots.metric("Completed Slots", f"{slot_num} / {t_slots}")
            m_speed.metric("Upload Speed", f"{speed} rows/s")

            if cum_uploaded >= tot_records:
                eta_str = "Complete"
            elif eta_sec >= 60:
                eta_str = f"{eta_sec // 60}m {eta_sec % 60}s"
            else:
                eta_str = f"{eta_sec}s"
            m_eta.metric("Estimated Time Left", eta_str)

            feed_entry = (
                f"- **Slot {slot_num}/{t_slots}**: Excel rows **{start_row} to {end_row}** "
                f"({uploaded_now:,} records) successfully uploaded to MySQL in {info.get('slot_elapsed_seconds', 0)}s "
                f"*(Speed: {speed} rows/s)*"
            )
            slot_feed_messages.append(feed_entry)
            feed_container.markdown("\n".join(slot_feed_messages))

        def update_progress(pct: float, msg: str):
            progress_bar.progress(min(1.0, max(0.0, pct)))
            status_text.text(msg)

        records_to_upload = st.session_state.get("mysql_uploader_parsed_records", dataset_source)
        first_ws = parsed_records[0].get("wholesaler_company_name") if parsed_records else None

        with st.spinner(f"Synchronizing with Remote MySQL ({active_config.host})..."):
            report = uploader_service.upload_dataset(
                dataset_source=records_to_upload,
                progress_callback=update_progress,
                slot_callback=handle_slot_notification,
                slot_size=effective_slot,
                batch_size=int(batch_size),
                auto_init_schema=True,
                upload_mode=upload_mode,
                clear_existing=clear_existing,
                wholesaler_name=first_ws,
            )

        if report.get("success"):
            for k in (
                "mysql_crud_metadata_cache",
                "mysql_crud_last_filter_sig",
                "mysql_crud_cached_total_count",
            ):
                st.session_state.pop(k, None)
            st.balloons()
            st.success(
                f"🎉 **MySQL Upload Successful!** Synchronized **{report['uploaded_count']:,} products** "
                f"into Remote MySQL database `{active_config.database}` (table `wholesale_products`) "
                f"across **{report.get('completed_slots', 0)} slots** in **{report.get('elapsed_seconds', 0)} seconds**."
            )
            if st.button("🗄️ Open Module 6: View & Manage MySQL Data", type="secondary", key="goto_mysql_crud_after_upload_btn"):
                st.session_state["active_module"] = "mysql_crud"
                st.rerun()
            if report.get("slot_logs"):
                with st.expander("📊 Complete Slot Breakdown Table", expanded=False):
                    summary_df = pd.DataFrame(
                        [
                            {
                                "Slot": s["slot_number"],
                                "Excel Data Rows": f"{s['start_row']} – {s['end_row']}",
                                "Records": s["slot_records_count"],
                                "Uploaded": s["slot_uploaded"],
                                "Failed": s["slot_failed"],
                                "Duration": f"{s['slot_elapsed_seconds']}s",
                                "Speed": f"{s['speed_records_per_sec']} rows/s",
                            }
                            for s in report["slot_logs"]
                        ]
                    )
                    st.dataframe(summary_df, use_container_width=True)
        else:
            st.error("❌ Remote MySQL upload encountered errors.")
            for err in report.get("errors", []):
                st.write(f"- {err}")
