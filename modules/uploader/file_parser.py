def _clean_sql_value(col: str, val: Any) -> Any:
    """
    Cleans an individual value into SQLite-friendly Python primitives:
    None, int, float, str.
    """
    if val is None or pd.isna(val):
        return None

    if isinstance(val, (datetime.datetime, datetime.date)):
        return val.strftime("%Y-%m-%d %H:%M:%S")

    s_val = str(val).strip()
    if s_val.lower() in ("nan", "none", "null", ""):
        return None

    if col in INTEGER_COLUMNS:
        # Strip commas or formatting
        s_clean = re.sub(r"[^\d-]", "", s_val)
        try:
            return int(float(s_clean))
        except (ValueError, TypeError):
            return None

    if col in NUMERIC_COLUMNS:
        # Clean currency or percentage symbols
        s_clean = re.sub(r"[^\d.-]", "", s_val)
        try:
            return round(float(s_clean), 4)
        except (ValueError, TypeError):
            return None

    if col == "favorite":
        if str(val).lower() in ("true", "1", "yes", "⭐"):
            return 1
        return 0

    return s_val


def parse_and_validate_analysis_file(
    source: Union[pd.DataFrame, str, Any]
) -> List[Dict[str, Any]]:
    """
    Parse an analysis file or DataFrame and produce sanitized database records.

    Args:
        source: A pandas DataFrame, file path, or uploaded file buffer.

    Returns:
        List[Dict[str, Any]]: List of dictionary rows matching SQLite table schema.
    """
    if source is None:
        return []

    # 1. Ingest into DataFrame
    if isinstance(source, pd.DataFrame):
        df = source.copy()
    else:
        # File path or Streamlit UploadedFile
        file_name = getattr(source, "name", str(source)).lower()
        if hasattr(source, "seek"):
            source.seek(0)

        if file_name.endswith(".csv"):
            for encoding in ["utf-8", "utf-8-sig", "latin1", "cp1252"]:
                try:
                    if hasattr(source, "seek"):
                        source.seek(0)
                    df = pd.read_csv(source, encoding=encoding)
                    break
                except UnicodeDecodeError:
                    continue
        else:
            if hasattr(source, "seek"):
                source.seek(0)
            df = pd.read_excel(source)

    if df.empty:
        return []

    # 2. Map Columns to SQL names
    sql_records = []
    df_cols = list(df.columns)

    # Pre-map header lookups
    col_mapping = {}
    for col in df_cols:
        cleaned_header = str(col).strip()
        if cleaned_header in TARGET_TO_SQL_COLUMN_MAP:
            col_mapping[col] = TARGET_TO_SQL_COLUMN_MAP[cleaned_header]
        else:
            # Fallback snake_case
            snake = re.sub(r"[^\w]+", "_", cleaned_header.lower()).strip("_")
            col_mapping[col] = snake

    for _, row in df.iterrows():
        record = {}
        for original_col, sql_col in col_mapping.items():
            raw_val = row.get(original_col)
            record[sql_col] = _clean_sql_value(sql_col, raw_val)

        # Fallback defaults for primary required fields
        if not record.get("asin"):
            # Check if Product ID can serve as ASIN if 10 chars starting with B
            p_id = str(record.get("product_id") or "").strip().upper()
            if len(p_id) == 10 and p_id.startswith("B"):
                record["asin"] = p_id

        if not record.get("wholesaler_company_name"):
            record["wholesaler_company_name"] = "Default Wholesale"

        if not record.get("analyzing_software_name"):
            record["analyzing_software_name"] = "InternalAMZ"

        # Timestamp tracking
        if not record.get("last_run"):
            record["last_run"] = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        sql_records.append(record)

    return sql_records


def validate_record_integrity(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Runs pre-flight validation checks on records prior to database ingestion.

    Args:
        records: List of parsed record dicts.

    Returns:
        Dict[str, Any]: Validation summary.
    """
    total = len(records)
    valid_count = 0
    missing_asin_count = 0
    missing_wholesaler_count = 0
    sample_valid_asins = []

    for r in records:
        asin = r.get("asin")
        wholesaler = r.get("wholesaler_company_name")

        has_asin = bool(asin and str(asin).strip() and str(asin).strip().upper() != "NOT_FOUND")
        has_wholesaler = bool(wholesaler and str(wholesaler).strip())

        if not has_asin:
            missing_asin_count += 1
        if not has_wholesaler:
            missing_wholesaler_count += 1

        if has_asin and has_wholesaler:
            valid_count += 1
            if len(sample_valid_asins) < 5:
                sample_valid_asins.append(asin)

    return {
        "total_records": total,
        "valid_count": valid_count,
        "invalid_count": total - valid_count,
        "missing_asin_count": missing_asin_count,
        "missing_wholesaler_count": missing_wholesaler_count,
        "sample_valid_asins": sample_valid_asins,
        "is_ready_for_upload": valid_count > 0,
    }
