"""
Module 3: Data Upload to Database - Streamlit User Interface
============================================================
Purpose:
    Renders the Streamlit interface for Module 3 (Upload to Cloudflare D1).
    Enables users to:
    - Input and securely test Cloudflare D1 credentials (Account ID, Database ID, API Token)
    - Persist credentials to .env file with one click
    - Initialize the remote `wholesale_products` table schema on Cloudflare D1
    - Select source data: active in-memory results from Module 2 or uploaded Excel/CSV file
    - Inspect pre-flight validation status (valid ASINs, data types, column checks)
    - Execute the batch upsert upload pipeline with a real-time progress bar
    - Seamlessly transition to Module 4 (Database CRUD & Viewer)
"""

import streamlit as st
import pandas as pd
from .config import CloudflareD1Config
from .d1_client import CloudflareD1Client
from .file_parser import parse_and_validate_analysis_file, validate_record_integrity
from .uploader_service import D1UploaderService


def render_uploader_ui():
    """
    Renders the complete user interface for Module 3: Data Upload to Cloudflare D1.
    """
    st.header("☁️ Module 3: Upload Data to Cloudflare D1 Database")
    st.markdown(
        "Upload the data generated by Module 2 or upload your file."
    )

    # --- SIDEBAR: CLOUDFLARE D1 CREDENTIALS ---
    st.sidebar.subheader("🔐 Cloudflare D1 Credentials")
    env_config = CloudflareD1Config.from_env()

    account_id = st.sidebar.text_input(
        "Cloudflare Account ID",
        value=st.session_state.get("cf_account_id", env_config.account_id),
        type="password",
        help="32-character hex ID found in your Cloudflare dashboard URL.",
        key="cf_account_id_input",
    )
    database_id = st.sidebar.text_input(
        "D1 Database ID (UUID)",
        value=st.session_state.get("cf_database_id", env_config.database_id),
        type="password",
        help="UUID of your target Cloudflare D1 database (e.g., xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx).",
        key="cf_database_id_input",
    )
    api_token = st.sidebar.text_input(
        "Cloudflare API Token",
        value=st.session_state.get("cf_api_token", env_config.api_token),
        type="password",
        help="API token with 'D1 Edit' permissions for your account.",
        key="cf_api_token_input",
    )

    st.sidebar.subheader("⚡ Upload Tuning")
    slot_size = st.sidebar.number_input(
        "Notification Slot Size (Records)",
        min_value=50,
        max_value=2000,
        value=int(st.session_state.get("cf_slot_size", 500)),
        step=50,
        help="Divide large uploads into slots of this size. Gives a confirmation notification after each slot.",
        key="cf_slot_size_input",
    )
    batch_size = st.sidebar.slider(
        "Batch Size (Rows per Request)",
        min_value=10,
        max_value=100,
        value=int(st.session_state.get("cf_batch_size", env_config.batch_size)),
        help="Number of rows per batch statement to comply with Cloudflare parameter boundaries.",
        key="cf_batch_size_slider",
    )

    # Save to session state
    st.session_state["cf_account_id"] = account_id.strip()
    st.session_state["cf_database_id"] = database_id.strip()
    st.session_state["cf_api_token"] = api_token.strip()
    st.session_state["cf_batch_size"] = batch_size
    st.session_state["cf_slot_size"] = slot_size

    active_config = CloudflareD1Config(
        account_id=st.session_state["cf_account_id"],
        database_id=st.session_state["cf_database_id"],
        api_token=st.session_state["cf_api_token"],
        batch_size=batch_size,
    )
    client = CloudflareD1Client(active_config)

    # Credential action buttons
    if st.sidebar.button("🧪 Test D1 Connection", key="test_d1_conn_btn", use_container_width=True):
        if not active_config.is_valid():
            st.sidebar.warning("Please provide Account ID, Database UUID, and API Token.")
        else:
            with st.sidebar.spinner("Testing connection..."):
                success, msg = client.test_connection()
            if success:
                st.sidebar.success(msg)
            else:
                st.sidebar.error(msg)

    with st.sidebar.expander("🛠️ Database Maintenance", expanded=False):
        if st.button("Initialize Table Schema", key="init_schema_btn", use_container_width=True):
            if not active_config.is_valid():
                st.warning("Please configure your Cloudflare credentials first.")
            else:
                with st.spinner("Initializing wholesale_products table in Cloudflare D1..."):
                    ok, msg = client.init_database_schema()
                if ok:
                    st.success(msg)
                else:
                    st.error(msg)

        if st.button("Migrate Schema (Allow All Duplicate ASINs)", key="migrate_schema_btn", use_container_width=True, help="Drops the old UNIQUE constraint on ASIN so that all variations and duplicate ASIN rows can be stored."):
            if not active_config.is_valid():
                st.warning("Please configure your Cloudflare credentials first.")
            else:
                with st.spinner("Migrating wholesale_products table in Cloudflare D1..."):
                    ok, msg = client.migrate_remove_unique_constraint()
                if ok:
                    st.success(msg)
                else:
                    st.error(msg)

        st.markdown("---")
        st.markdown("**Clear Database Table**")
        confirm_clear = st.checkbox("Confirm wipe all data", key="confirm_clear_chk")
        if st.button("🗑️ Clear wholesale_products Table", key="clear_table_btn", use_container_width=True, type="secondary"):
            if not active_config.is_valid():
                st.warning("Please configure your Cloudflare credentials first.")
            elif not confirm_clear:
                st.warning("Please check 'Confirm wipe all data' first.")
            else:
                with st.spinner("Clearing wholesale_products table..."):
                    ok, msg = client.clear_table()
                if ok:
                    st.success(msg)
                else:
                    st.error(msg)

    st.sidebar.markdown("---")

    # --- MAIN VIEW: DATA SOURCE SELECTION ---
    st.subheader("1. Select Dataset to Upload")

    has_pending = "pending_d1_upload" in st.session_state and st.session_state["pending_d1_upload"] is not None

    source_mode = st.radio(
        "Choose Data Source:",
        ["📦 In-Memory Analysis from Module 2", "📁 Upload Target Analysis File (.xlsx or .csv)"],
        index=0 if has_pending else 1,
        key="uploader_source_mode",
    )

    dataset_source = None

    if "In-Memory" in source_mode:
        if has_pending:
            dataset_source = st.session_state["pending_d1_upload"]
            st.success(f"✅ In-memory analysis loaded from Module 2 (**{len(dataset_source)} products** ready).")
        else:
            st.info("ℹ️ No active analysis found in memory. You can switch to Module 2 to analyze a catalog, or upload a saved file below.")
    else:
        uploaded_analysis_file = st.file_uploader(
            "Upload Saved Target Analysis File (.xlsx or .csv)",
            type=["xlsx", "csv"],
            key="uploader_file_input",
            help="Upload an Excel or CSV file generated from Module 2.",
        )
        if uploaded_analysis_file:
            dataset_source = uploaded_analysis_file
            st.success(f"File `{uploaded_analysis_file.name}` uploaded.")

    if dataset_source is None:
        return

    # --- PRE-FLIGHT VERIFICATION ---
    st.subheader("2. Pre-Flight Data Validation & Preview")
    
    with st.spinner("Parsing and validating columns..."):
        try:
            parsed_records = parse_and_validate_analysis_file(dataset_source)
            integrity = validate_record_integrity(parsed_records)
            st.session_state["uploader_parsed_records"] = parsed_records
        except Exception as e:
            st.error(f"Error parsing source dataset: {e}")
            return

    # Metrics Row
    m1, m2, m3, m4, m5 = st.columns(5)
    m1.metric("Total Rows in File", f"{integrity['total_records']:,}")
    m2.metric("Valid Products to DB", f"{integrity['valid_count']:,}")
    m3.metric("Missing ASINs", f"{integrity['missing_asin_count']:,}")
    m4.metric("Unique ASINs", f"{integrity.get('unique_asin_count', integrity['valid_count']):,}")
    m5.metric("Variations / Same ASIN", f"{integrity.get('duplicate_asin_count', 0):,}")

    if integrity["valid_count"] == 0:
        st.error("⚠️ No valid products with recognized ASINs were found in this dataset. Please verify the file.")
        return

    dup_count = integrity.get("duplicate_asin_count", 0)
    if dup_count > 0:
        st.info(
            f"ℹ️ **Catalog Structure Notice**: Found **{dup_count:,} catalog items** "
            f"sharing an ASIN with other rows (e.g. variations, different UPC barcodes, pack sizes). "
            f"**All {integrity['valid_count']:,} records will be preserved in Cloudflare D1** "
            f"(no rows will be merged or discarded)."
        )

    effective_slot = int(st.session_state.get("cf_slot_size", slot_size))
    total_valid = integrity["valid_count"]
    estimated_slots = max(1, (total_valid + effective_slot - 1) // effective_slot)

    if total_valid > effective_slot:
        st.info(
            f"💡 **Smart Slot Batching Active**: Dataset with **{total_valid:,} records** "
            f"will be written safely in slots of **{effective_slot} records** (~**{estimated_slots} slots**). "
            f"You will receive a notification and row confirmation every time {effective_slot} records are written to the database."
        )

    with st.expander("👁️ Preview Parsed Database Records (First 5 Rows)", expanded=True):
        preview_df = pd.DataFrame(parsed_records[:5])
        display_subcols = [
            c for c in [
                "asin", "product_id", "wholesaler_company_name", "brand", "title",
                "category", "sales_rank", "cost", "sell_price", "profit", "roi_pct"
            ] if c in preview_df.columns
        ]
        st.dataframe(preview_df[display_subcols] if display_subcols else preview_df, use_container_width=True)

    # --- UPLOAD EXECUTION ---
    st.subheader("3. Execute Cloudflare D1 Synchronization")

    c_opt1, c_opt2 = st.columns(2)
    with c_opt1:
        upload_mode_choice = st.radio(
            "Upload Strategy:",
            [
                "📥 Insert All Records (Preserve every catalog row & duplicate ASINs)",
                "🔄 Upsert / Deduplicate by ASIN (Merge records matching same ASIN + Wholesaler)",
            ],
            index=0,
            key="cf_upload_mode_choice",
            help="Insert All Records guarantees that all 4,987 valid catalog items are written to Cloudflare D1.",
        )
        upload_mode = "insert" if "Insert All" in upload_mode_choice else "upsert"

    with c_opt2:
        cleanup_choice = st.selectbox(
            "Existing Database Records Handling:",
            [
                "Keep existing database records (Append mode)",
                "Clear entire database table before upload (Fresh start - DB count matches file)",
                "Replace records for this wholesaler only",
            ],
            index=0,
            key="cf_cleanup_choice",
            help="Choose whether to wipe previous records so your database count exactly matches this file.",
        )
        if "Clear entire" in cleanup_choice:
            clear_existing = "all"
        elif "Replace records for this wholesaler" in cleanup_choice:
            clear_existing = "wholesaler"
        else:
            clear_existing = "none"

    if clear_existing == "all":
        st.warning("⚠️ **Notice**: The `wholesale_products` table will be cleared before uploading. Your database will contain only the records from this upload.")

    if not active_config.is_valid():
        st.warning("⚠️ Please provide your **Cloudflare Account ID**, **Database UUID**, and **API Token** in the sidebar before starting the upload.")
        return

    if st.button("🚀 Start Upload to Cloudflare D1", type="primary", key="start_d1_upload_btn"):
        uploader_service = D1UploaderService(client)

        # Real-time metrics dashboard
        m_col1, m_col2, m_col3, m_col4 = st.columns(4)
        m_uploaded = m_col1.empty()
        m_slots = m_col2.empty()
        m_speed = m_col3.empty()
        m_eta = m_col4.empty()

        m_uploaded.metric("Uploaded Records", f"0 / {total_valid:,}")
        m_slots.metric("Completed Slots", f"0 / {estimated_slots}")
        m_speed.metric("Upload Speed", "0.0 rows/s")
        m_eta.metric("Estimated Time Left", "--")

        progress_bar = st.progress(0.0)
        status_text = st.empty()

        feed_expander = st.expander("📋 Live Slot Confirmations & Audit Log", expanded=True)
        feed_container = feed_expander.empty()
        slot_feed_messages = []

        def handle_slot_notification(info: dict):
            slot_num = info.get("slot_number", 1)
            t_slots = info.get("total_slots", 1)
            start_row = info.get("start_row", 1)
            end_row = info.get("end_row", 1)
            uploaded_now = info.get("slot_uploaded", 0)

            # 1. Pop up a toast notification on the user's screen
            toast_text = f"✅ Slot {slot_num}/{t_slots}: Excel rows {start_row} to {end_row} complete upload to database!"
            try:
                st.toast(toast_text, icon="💾")
            except Exception:
                pass

            # 2. Update KPI metrics
            cum_uploaded = info.get("cumulative_uploaded", 0)
            tot_records = info.get("total_records", total_valid)
            speed = info.get("speed_records_per_sec", 0.0)
            eta_sec = info.get("eta_seconds", 0)

            m_uploaded.metric("Uploaded Records", f"{cum_uploaded:,} / {tot_records:,}")
            m_slots.metric("Completed Slots", f"{slot_num} / {t_slots}")
            m_speed.metric("Upload Speed", f"{speed} rows/s")

            if cum_uploaded >= tot_records:
                eta_str = "Complete"
            elif eta_sec >= 60:
                eta_str = f"{eta_sec // 60}m {eta_sec % 60}s"
            else:
                eta_str = f"{eta_sec}s"
            m_eta.metric("Estimated Time Left", eta_str)

            # 3. Log to live feed container
            feed_entry = (
                f"- **Slot {slot_num}/{t_slots}**: Excel rows **{start_row} to {end_row}** "
                f"({uploaded_now:,} records) successfully uploaded in {info.get('slot_elapsed_seconds', 0)}s "
                f"*(Speed: {speed} rows/s)*"
            )
            slot_feed_messages.append(feed_entry)
            feed_container.markdown("\n".join(slot_feed_messages))

        def update_progress(pct: float, msg: str):
            progress_bar.progress(min(1.0, max(0.0, pct)))
            status_text.text(msg)

        # Use pre-parsed records directly to avoid re-parsing large datasets
        records_to_upload = st.session_state.get("uploader_parsed_records", dataset_source)

        # Extract wholesaler name from parsed records if available
        first_ws = parsed_records[0].get("wholesaler_company_name") if parsed_records else None

        with st.spinner("Synchronizing with Cloudflare D1..."):
            report = uploader_service.upload_dataset(
                dataset_source=records_to_upload,
                progress_callback=update_progress,
                slot_callback=handle_slot_notification,
                slot_size=effective_slot,
                batch_size=batch_size,
                auto_init_schema=True,
                upload_mode=upload_mode,
                clear_existing=clear_existing,
                wholesaler_name=first_ws,
            )

        if report.get("success"):
            st.balloons()
            st.success(
                f"🎉 **Upload Successful!** Synchronized **{report['uploaded_count']:,} products** "
                f"into Cloudflare D1 table `wholesale_products` across **{report.get('completed_slots', 0)} slots** "
                f"in **{report.get('elapsed_seconds', 0)} seconds**."
            )
            if report.get("slot_logs"):
                with st.expander("📊 Complete Slot Breakdown Table", expanded=False):
                    summary_df = pd.DataFrame([
                        {
                            "Slot": s["slot_number"],
                            "Excel Data Rows": f"{s['start_row']} – {s['end_row']}",
                            "Records": s["slot_records_count"],
                            "Uploaded": s["slot_uploaded"],
                            "Failed": s["slot_failed"],
                            "Duration": f"{s['slot_elapsed_seconds']}s",
                            "Speed": f"{s['speed_records_per_sec']} rows/s",
                        }
                        for s in report["slot_logs"]
                    ])
                    st.dataframe(summary_df, use_container_width=True)
        else:
            st.error("❌ Database upload encountered errors.")
            for err in report.get("errors", []):
                st.write(f"- {err}")
